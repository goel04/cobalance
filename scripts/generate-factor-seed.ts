// Generates supabase/migrations/*_seed_emission_factors.sql from the tested
// library in src/lib/engine/factors.ts, so the database and the engine never
// disagree about a factor value.
//   npx vite-node scripts/generate-factor-seed.ts
import { writeFileSync } from 'node:fs';
import { DEFAULT_FACTORS } from '../src/lib/engine/factors';

const OUT = 'supabase/migrations/20261026000003_seed_emission_factors.sql';

const lit = (v: string) => `'${v.replace(/'/g, "''")}'`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;

const rows = DEFAULT_FACTORS.map((f) => {
  // Deterministic id: re-running the migration never duplicates a factor.
  const id = `md5(${lit(`cobalance-library:${f.factorCode}:${f.version}`)})::uuid`;
  return `  (${[
    id,
    lit(f.factorCode),
    lit(f.category),
    lit(f.subtype),
    lit(f.activityUnit),
    json(f.components),
    lit(f.factorUnit),
    lit(f.geography),
    `${lit(f.validFrom)}::date`,
    f.validTo ? `${lit(f.validTo)}::date` : 'null',
    String(f.publicationYear),
    lit(f.sourceName),
    lit(f.sourceUrl),
    lit(f.methodology),
    lit(f.version),
    lit(f.gwpReference),
    lit(f.reviewStatus),
    `'library'`,
    f.conversions ? json(f.conversions) : 'null',
    lit(f.notes ?? ''),
  ].join(', ')})`;
});

const sql = `-- Shared emission-factor library (company_id is null). GENERATED by
-- scripts/generate-factor-seed.ts from src/lib/engine/factors.ts — edit the
-- TypeScript source and regenerate rather than editing this file.
-- The CEA grid factor is seeded as 'provisional' until confirmed against the
-- published CEA document. Coal, purchased steam and all Scope 3 categories have
-- no library factor on purpose: those activities show "awaiting factor".

insert into public.emission_factors (
  id, factor_code, category, subtype, activity_unit, components, factor_unit, geography,
  valid_from, valid_to, publication_year, source_name, source_url, methodology, version,
  gwp_reference, review_status, origin, conversions, notes
) values
${rows.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync(OUT, sql);
console.log(`Wrote ${DEFAULT_FACTORS.length} factors to ${OUT}`);
